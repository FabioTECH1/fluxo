func networkDatabase(t *testing.T) string {
	t.Helper()
	old := DB
	file := filepath.Join(t.TempDir(), "base.db")
	if e := InitBaseDB(file); e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() {
		if DB != nil && DB != old {
			DB.Close()
		}
		DB = old
	})
	return file
}
func TestSiteNetworkAdditiveInitializationPreservesState(t *testing.T) {
	file := networkDatabase(t)
	var identity string
	DB.QueryRow("SELECT value FROM system_metadata WHERE key='installation_id'").Scan(&identity)
	if _, e := DB.Exec("DROP TABLE site_network_operations; DROP TABLE site_network_settings;"); e != nil {
		t.Fatal(e)
	}
	if e := ValidateCurrentSchema(context.Background(), DB); e != nil {
		t.Fatal("rejected supported absent extension", e)
	}
	DB.Close()
	if e := InitBaseDB(file); e != nil {
		t.Fatal(e)
	}
	var after string
	DB.QueryRow("SELECT value FROM system_metadata WHERE key='installation_id'").Scan(&after)
	if after != identity || after == "" {
		t.Fatal("changed original identity")
	}
	_, e := DB.Exec("INSERT INTO sites(id,domain,path,deploy_script) VALUES(7,'example.test','/home/fluxo/example.test','custom user script')")
	if e != nil {
		t.Fatal(e)
	}
	settings := EmptySiteNetwork()
	settings.Username = "retained-user"
	settings.Redirects = []SiteRedirect{{ID: "id", Source: "/old", Destination: "/new", Status: 302}}
	tx, _ := DB.Begin()
	if e = SaveSiteNetworkTx(tx, 7, settings); e != nil {
		t.Fatal(e)
	}
	if e = tx.Commit(); e != nil {
		t.Fatal(e)
	}
	var before string
	DB.QueryRow("SELECT settings FROM site_network_settings WHERE site_id=7").Scan(&before)
	DB.Close()
	if e = InitBaseDB(file); e != nil {
		t.Fatal(e)
	}
	var actual, script string
	DB.QueryRow("SELECT settings FROM site_network_settings WHERE site_id=7").Scan(&actual)
	DB.QueryRow("SELECT deploy_script FROM sites WHERE id=7").Scan(&script)
	if before != actual || script != "custom user script" {
		t.Fatal("rewrote saved settings or script")
	}
}
func TestSiteNetworkPartialAndMalformedStorageRefusesWithoutRepair(t *testing.T) {
	for _, damage := range []string{"DROP TABLE site_network_operations", "DROP TABLE site_network_settings; CREATE TABLE site_network_settings(site_id INTEGER PRIMARY KEY,settings BLOB)"} {
		t.Run(damage, func(t *testing.T) {
			file := networkDatabase(t)
			if _, e := DB.Exec(damage); e != nil {
				t.Fatal(e)
			}
			DB.Close()
			before, _ := os.ReadFile(file)
			if e := InitBaseDB(file); e == nil {
				t.Fatal("repaired damaged extension")
			}
			after, _ := os.ReadFile(file)
			if sha256.Sum256(before) != sha256.Sum256(after) {
				t.Fatal("mutated refused database")
			}
		})
	}
}
func TestSiteNetworkPendingOperationRetainsHistory(t *testing.T) {
	networkDatabase(t)
	if _, e := DB.Exec("INSERT INTO sites(id,domain,path)VALUES(7,'example.test','/home/fluxo/example.test')"); e != nil {
		t.Fatal(e)
	}
	if e := BeginSiteNetworkOperation("operation", 7, "previous generated bytes", "revision"); e != nil {
		t.Fatal(e)
	}
	if e := BeginSiteNetworkOperation("second", 7, "other", "revision"); e == nil {
		t.Fatal("duplicate pending operation")
	}
	p, e := PendingSiteNetwork(7)
	if e != nil || p.ID != "operation" || p.PreviousConfig != "previous generated bytes" {
		t.Fatal(p, e)
	}
	if e = FinishSiteNetworkOperation("operation", "rolled_back"); e != nil {
		t.Fatal(e)
	}
	p, e = PendingSiteNetwork(7)
	if e != nil || p != nil {
		t.Fatal(p, e)
	}
	var n int
	DB.QueryRow("SELECT count(*) FROM site_network_operations").Scan(&n)
	if n != 1 {
		t.Fatal("erased recovery history")
	}
}

func TestSiteNetworkDeploymentAdmissionIsReciprocal(t *testing.T) {
	networkDatabase(t)
	if _, e := DB.Exec("INSERT INTO sites(id,domain,path)VALUES(7,'example.test','/unused')"); e != nil {
		t.Fatal(e)
	}
	if e := BeginSiteNetworkOperation("network", 7, "old config", "revision"); e != nil {
		t.Fatal(e)
	}
	if _, e := DB.Exec("INSERT INTO deployments(id,site_id,status)VALUES(1,7,'pending')"); e != nil {
		t.Fatal(e)
	}
	if claimed, e := ClaimPendingDeployment(1, 7); e != nil || claimed {
		t.Fatal("admitted deployment during interrupted network activation", claimed, e)
	}
	if e := FinishSiteNetworkOperation("network", "rolled_back"); e != nil {
		t.Fatal(e)
	}
	if e := BeginSiteNetworkOperation("queued", 7, "old config", "revision"); e == nil {
		t.Fatal("activated network over queued deployment")
	}
	if claimed, e := ClaimPendingDeployment(1, 7); e != nil || !claimed {
		t.Fatal("did not resume deployment after recovery", claimed, e)
	}
	if e := BeginSiteNetworkOperation("running", 7, "old config", "revision"); e == nil {
		t.Fatal("activated network over running deployment")
	}
	if _, e := DB.Exec("UPDATE deployments SET status='success' WHERE id=1"); e != nil {
		t.Fatal(e)
	}
	if e := BeginSiteNetworkOperation("finished", 7, "old config", "revision"); e != nil {
		t.Fatal(e)
	}
}
